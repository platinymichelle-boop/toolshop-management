"use client";

import { useState } from "react";
import { supabase } from "@/lib/supabase";
import { useRouter } from "next/navigation";
import { LogIn, UserPlus, Loader2 } from "lucide-react";

export default function LoginPage() {
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [fullName, setFullName] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const [isSignUpMode, setIsSignUpMode] = useState(false);
  const router = useRouter();

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    setIsLoading(true);

    const cleanEmail = email.trim().toLowerCase();

    try {
      if (isSignUpMode) {
        // ================= ACȚIUNE: SIGN UP (Înregistrare Cont Nou) =================
        if (!fullName.trim()) {
          alert("Te rog introdu numele tău complet pentru înregistrare.");
          setIsLoading(false);
          return;
        }

        // 1. Înregistrăm mai întâi utilizatorul în modulul central de securitate Supabase Auth
        const { data: signUpData, error: signUpError } =
          await supabase.auth.signUp({
            email: cleanEmail,
            password: password,
          });

        if (signUpError) throw signUpError;

        // 2. Inserăm direct în tabela publică users.
        // Lăsăm coloana "id" goală pentru ca baza de date să folosească "generated by default as identity" (bigint) văzut în SQL!
        const { error: profileError } = await supabase.from("users").insert([
          {
            username: cleanEmail,
            full_name: fullName.trim(),
            role: "user",
            active: true,
            can_view_repairs: false,
            can_view_tools: false,
            can_view_parts: false,
            can_view_reports: false,
          },
        ]);

        if (profileError) {
          throw new Error(
            `Profilul public nu a putut fi creat: ${profileError.message}`,
          );
        }

        alert(
          "Contul de tehnician a fost înregistrat cu succes! Acum te poți conecta.",
        );
        setIsSignUpMode(false);
        setFullName("");
        setPassword("");
      } else {
        // ================= ACȚIUNE: LOG IN (Conectare Cont Existent) =================
        // 1. Autentificăm utilizatorul în Supabase Auth
        const { error: authError } = await supabase.auth.signInWithPassword({
          email: cleanEmail,
          password: password,
        });

        if (authError) throw authError;

        // 2. Extragem drepturile din tabela publică utilizând coloana username definită în SQL
        const { data: userData, error: userError } = await supabase
          .from("users")
          .select("role, active")
          .eq("username", cleanEmail)
          .maybeSingle();

        if (userError) {
          console.error(
            "Eroare la citirea matricei din tabela users:",
            userError.message,
          );
        }

        // 3. Verificăm dacă administratorul a blocat acest cont din matricea GPO
        if (userData && userData.active === false) {
          await supabase.auth.signOut();
          alert(
            "Acest cont a fost dezactivat de un administrator în panoul de control.",
          );
          return;
        }

        router.push("/maintenance-reports");
      }
    } catch (error: any) {
      alert("Sistem Validare: " + error.message);
    } finally {
      setIsLoading(false);
    }
  }
  return (
    <div className="fixed inset-0 bg-gradient-to-tr from-slate-950 via-slate-900 to-slate-950 flex items-center justify-center p-4 z-50 font-sans">
      <div className="bg-white p-8 rounded-2xl shadow-2xl w-full max-w-md border border-slate-100 flex flex-col justify-between transform transition-all duration-300">
        {/* Titlu și Brand Industrial */}
        <div className="text-center space-y-2">
          <div className="w-12 h-12 bg-indigo-50 border border-indigo-100 text-indigo-600 rounded-xl flex items-center justify-center mx-auto text-xl shadow-inner font-black">
            ⚙️
          </div>
          <h1 className="text-2xl font-black text-slate-900 tracking-tight">
            MEtal Stamping Maintenance
          </h1>
          <p className="text-xs text-slate-500 uppercase tracking-wider font-bold">
            {isSignUpMode
              ? "Creare Profil Tehnic"
              : "Sistem de Gestiune și Control Service"}
          </p>
        </div>

        {/* Formular Unificat */}
        <form onSubmit={handleSubmit} className="space-y-4 mt-6">
          {isSignUpMode && (
            <div className="transition-all duration-300">
              <label className="text-xs font-bold text-slate-500 uppercase tracking-wide block mb-1">
                Nume și Prenume Angajat
              </label>
              <input
                type="text"
                required
                className="w-full bg-slate-50 border border-slate-200 rounded-xl p-3 text-sm focus:outline-none focus:border-indigo-500 text-slate-900 shadow-inner"
                placeholder="Ex: Popescu Ionut"
                value={fullName}
                onChange={(e) => setFullName(e.target.value)}
                disabled={isLoading}
              />
            </div>
          )}

          <div>
            <label className="text-xs font-bold text-slate-500 uppercase tracking-wide block mb-1">
              Email / Username Corporativ
            </label>
            <input
              type="email"
              required
              className="w-full bg-slate-50 border border-slate-200 rounded-xl p-3 text-sm focus:outline-none focus:border-indigo-500 text-slate-900 shadow-inner"
              placeholder="nume.prenume@companie.com"
              value={email}
              onChange={(e) => setEmail(e.target.value)}
              disabled={isLoading}
            />
          </div>

          <div>
            <label className="text-xs font-bold text-slate-500 uppercase tracking-wide block mb-1">
              Parolă Acces
            </label>
            <input
              type="password"
              required
              className="w-full bg-slate-50 border border-slate-200 rounded-xl p-3 text-sm focus:outline-none focus:border-indigo-500 text-slate-900 shadow-inner"
              placeholder="••••••••"
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              disabled={isLoading}
            />
          </div>

          {/* Buton de trimitere dinamic */}
          <button
            type="submit"
            disabled={isLoading}
            className="w-full bg-indigo-600 hover:bg-indigo-500 disabled:bg-slate-100 disabled:text-slate-400 font-bold p-3.5 rounded-xl text-xs text-white transition-all shadow-md flex items-center justify-center gap-2 border border-indigo-500/20 active:scale-95"
          >
            {isLoading ? (
              <Loader2 className="w-4 h-4 animate-spin" />
            ) : isSignUpMode ? (
              <UserPlus className="w-4 h-4" />
            ) : (
              <LogIn className="w-4 h-4" />
            )}
            <span>
              {isLoading
                ? "Se procesează baza de date..."
                : isSignUpMode
                  ? "Înregistrează Cont"
                  : "Conectare în Panou"}
            </span>
          </button>
        </form>

        {/* Link de schimbare mod în subsol */}
        <div className="text-center pt-4 border-t border-slate-100 mt-6">
          <button
            type="button"
            onClick={() => {
              setIsSignUpMode(!isSignUpMode);
              setFullName("");
            }}
            disabled={isLoading}
            className="text-xs font-bold text-indigo-600 hover:text-indigo-500 tracking-wide transition-colors"
          >
            {isSignUpMode
              ? "Ai deja un cont creat? Mergi la Conectare"
              : "Nu ai un cont înregistrat? Creează unul acum"}
          </button>
        </div>
      </div>
    </div>
  );
}
